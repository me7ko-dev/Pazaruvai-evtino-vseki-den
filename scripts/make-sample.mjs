let seed = 7;
const rnd = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);
fs.mkdirSync('sample', { recursive: true });
const q = (s) => (/[",]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);
for (const [file, stores] of Object.entries(chains)) {
  const lines = ['Населено място,Търговски обект,Наименование на продукта,Код на продукта,Категория,Цена на дребно,Цена в промоция'];
  const chainFactor = 0.85 + rnd() * 0.3;
  for (const [city, addr] of stores) {
    for (const [cat, names, base] of cats) {
      if (rnd() < 0.08) continue; // някои магазини нямат някой продукт
      for (const name of names) {
        const price = (base * chainFactor * (0.9 + rnd() * 0.35)).toFixed(2);
        const promo = rnd() < 0.15 ? (price * 0.8).toFixed(2) : '';
        lines.push([city, addr, name, String(Math.floor(rnd() * 1e6)), cat, price.replace('.', ','), promo.replace('.', ',')].map(q).join(','));
      }
    }
  }
  fs.writeFileSync(`sample/${file}.csv`, lines.join('\n') + '\n');
}
